/**
 * Offline checks for the zlak-flow GitHub Copilot package.
 *
 * - The skill has name and description, disables model invocation, and ends with the run input.
 * - The custom agent's tools are exactly read and search: no edit, no execute.
 * - install.mjs installs into a chosen directory, is idempotent, and never overwrites a
 *   changed file without --force.
 */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(root + path, "utf8");

/** Split a markdown file into flat frontmatter fields and body. */
const frontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  assert.ok(match, "frontmatter present");
  const fields = {};
  for (const line of match[1].split("\n")) {
    const pair = line.match(/^([a-z-]+):\s*(.*)$/);
    if (pair) fields[pair[1]] = pair[2];
  }
  return { fields, body: match[2] };
};

const skill = frontmatter(read("skills/zlak-flow/SKILL.md"));
const agent = frontmatter(read("agents/zlak-flow-readonly.agent.md"));
const install = (...args) =>
  spawnSync("node", [`${root}install.mjs`, ...args], { encoding: "utf8" });

test("the skill has frontmatter, is explicit-only and ends with the run input", () => {
  assert.equal(skill.fields.name, "zlak-flow");
  assert.ok(skill.fields.description.length > 40);
  assert.equal(skill.fields["disable-model-invocation"], "true");
  assert.ok(skill.body.includes("Generated by packages/core"));
  assert.match(skill.body.trimEnd(), /read the message itself\.$/);
});

test("the read-only agent has only the read and search tools", () => {
  assert.equal(agent.fields.name, "zlak-flow-readonly");
  assert.equal(agent.fields.tools, "['read', 'search']");
  assert.doesNotMatch(agent.fields.tools, /edit|execute|\*/);
});

test("the config template is a generated, parseable copy", () => {
  JSON.parse(read("config/coder.example.json"));
});

test("install.mjs installs the skill and agent, then reports up to date", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-copilot-`);
  const dry = install("--target", target, "--dry-run");
  assert.equal(dry.status, 0);
  assert.match(dry.stdout, /would install/);
  assert.equal(readdirSync(target).length, 0, "dry run writes nothing");
  const first = install("--target", target);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(
    read("skills/zlak-flow/SKILL.md"),
    readFileSync(`${target}/skills/zlak-flow/SKILL.md`, "utf8"),
  );
  assert.equal(
    read("agents/zlak-flow-readonly.agent.md"),
    readFileSync(`${target}/agents/zlak-flow-readonly.agent.md`, "utf8"),
  );
  assert.match(install("--target", target).stdout, /up to date/);
});

test("install.mjs refuses to overwrite a changed file without --force", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-copilot-`);
  install("--target", target);
  writeFileSync(`${target}/skills/zlak-flow/SKILL.md`, "my edits\n");
  const refused = install("--target", target);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /--force/);
  assert.equal(
    readFileSync(`${target}/skills/zlak-flow/SKILL.md`, "utf8"),
    "my edits\n",
  );
  assert.equal(install("--target", target, "--force").status, 0);
  assert.equal(
    readFileSync(`${target}/skills/zlak-flow/SKILL.md`, "utf8"),
    read("skills/zlak-flow/SKILL.md"),
  );
  assert.equal(install("--nope").status, 2);
});
