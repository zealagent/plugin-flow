/**
 * Offline checks for the zlak-flow OpenCode package.
 *
 * - The command has frontmatter, ends with $ARGUMENTS and holds no other placeholder or
 *   shell block OpenCode would expand ($1..$N, !`cmd`).
 * - The planner and reviewer deny edits and every shell command except read-only git;
 *   the coder denies git commit and git push. Only the verified permission keys are used.
 * - install.mjs installs into a chosen directory, is idempotent, and never overwrites a
 *   changed file without --force.
 */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(root + path, "utf8");

/** Split a markdown file into raw frontmatter text, flat fields and body. */
const frontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  assert.ok(match, "frontmatter present");
  const fields = {};
  for (const line of match[1].split("\n")) {
    const pair = line.match(/^([a-z]+):\s*(.*)$/);
    if (pair) fields[pair[1]] = pair[2];
  }
  return { raw: match[1], fields, body: match[2] };
};

/** The permission rules of an agent as { action, resource, effect } objects, in order. */
const rules = (raw) =>
  [
    ...raw.matchAll(
      /- action: "?([^"\n]+)"?\n\s+resource: "?([^"\n]+)"?\n\s+effect: (\w+)/g,
    ),
  ].map((m) => ({ action: m[1], resource: m[2], effect: m[3] }));

/** The last element matching a predicate (rules are evaluated last match wins). */
const findLast = (list, test) => [...list].reverse().find(test);

const command = frontmatter(read("commands/zlak-flow.md"));
const agent = (name) => frontmatter(read(`agents/${name}.md`));
const install = (...args) =>
  spawnSync("node", [`${root}install.mjs`, ...args], { encoding: "utf8" });

test("the command has frontmatter and ends with the run input", () => {
  assert.ok(command.fields.description.length > 40);
  assert.ok(command.body.includes("Generated by packages/core"));
  assert.ok(command.body.trimEnd().endsWith("$ARGUMENTS"));
});

test("the command holds no placeholder or shell block OpenCode would expand", () => {
  assert.equal(command.body.match(/\$ARGUMENTS/g)?.length, 1);
  assert.doesNotMatch(command.body, /\$\d/, "no $1..$N positional placeholder");
  assert.doesNotMatch(command.body, /!`/, "no !`shell` block");
  assert.ok(!("agent" in command.fields), "runs in the current agent");
});

for (const name of ["zlak-flow-planner", "zlak-flow-reviewer"]) {
  test(`${name} is a read-only subagent`, () => {
    const { fields, raw, body } = agent(name);
    assert.equal(fields.mode, "subagent");
    assert.doesNotMatch(
      raw,
      /^(tools|permission):/m,
      "legacy keys are not used",
    );
    const list = rules(raw);
    const last = (action, resource) =>
      findLast(
        list,
        (r) =>
          r.action === action &&
          (r.resource === resource || r.resource === "*"),
      );
    assert.equal(last("edit", "*")?.effect, "deny");
    assert.equal(last("shell", "*")?.effect, "deny");
    assert.equal(last("subagent", "*")?.effect, "deny");
    for (const read of [
      "git status *",
      "git diff *",
      "git log *",
      "git show *",
    ]) {
      assert.equal(last("shell", read)?.effect, "allow", read);
    }
    for (const write of ["git commit *", "git push *", "rm *"]) {
      const exact = findLast(
        list,
        (r) => r.action === "shell" && r.resource === write,
      );
      assert.ok(!exact || exact.effect === "deny", write);
    }
    assert.match(body, /cannot edit files/);
  });
}

test("the coder edits but can neither commit nor push", () => {
  const { fields, raw } = agent("zlak-flow-coder");
  assert.equal(fields.mode, "subagent");
  const list = rules(raw);
  for (const resource of ["git commit *", "git push *"]) {
    assert.equal(
      findLast(list, (r) => r.action === "shell" && r.resource === resource)
        ?.effect,
      "deny",
    );
  }
  assert.ok(!list.some((r) => r.action === "edit" && r.effect === "deny"));
});

test("install.mjs installs commands and agents, then reports up to date", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-opencode-`);
  const dry = install("--target", target, "--dry-run");
  assert.equal(dry.status, 0);
  assert.match(dry.stdout, /would install/);
  assert.equal(readdirSync(target).length, 0, "dry run writes nothing");
  const first = install("--target", target);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(
    read("commands/zlak-flow.md"),
    readFileSync(`${target}/commands/zlak-flow.md`, "utf8"),
  );
  assert.deepEqual(
    readdirSync(`${target}/agents`).sort(),
    readdirSync(`${root}agents`).sort(),
  );
  assert.match(install("--target", target).stdout, /up to date/);
});

test("install.mjs refuses to overwrite a changed file without --force", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-opencode-`);
  install("--target", target);
  writeFileSync(`${target}/agents/zlak-flow-coder.md`, "my edits\n");
  const refused = install("--target", target);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /--force/);
  assert.equal(
    readFileSync(`${target}/agents/zlak-flow-coder.md`, "utf8"),
    "my edits\n",
  );
  assert.equal(install("--target", target, "--force").status, 0);
  assert.equal(
    readFileSync(`${target}/agents/zlak-flow-coder.md`, "utf8"),
    read("agents/zlak-flow-coder.md"),
  );
  assert.equal(install("--nope").status, 2);
});
