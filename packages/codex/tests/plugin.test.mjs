/**
 * Offline checks for the zlak-flow Codex CLI skill.
 *
 * - SKILL.md has frontmatter (name, description) and ends with the run input.
 * - SKILL.md and the config template are the generated copies from packages/core.
 * - agents/openai.yaml turns implicit invocation off.
 * - install.sh installs into a chosen directory, is idempotent, and never overwrites
 *   a changed copy without --force.
 */
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(root + path, "utf8");

/** Split a markdown file into its YAML frontmatter fields and body. */
const frontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  assert.ok(match, "frontmatter present");
  const fields = {};
  for (const line of match[1].split("\n")) {
    const pair = line.match(/^([a-z-]+):\s*(.*)$/);
    if (pair) fields[pair[1]] = pair[2];
  }
  return { fields, body: match[2] };
};

const skill = frontmatter(read("skills/zlak-flow/SKILL.md"));
const install = (...args) =>
  spawnSync("bash", [`${root}install.sh`, ...args], { encoding: "utf8" });

test("skill has frontmatter and ends with the run input", () => {
  assert.equal(skill.fields.name, "zlak-flow");
  assert.ok(skill.fields.description.length > 40);
  assert.ok(skill.body.includes("Generated by packages/core"));
  assert.match(skill.body.trimEnd(), /read the message itself\.$/);
  assert.doesNotMatch(skill.body, /\$ARGUMENTS/);
});

test("implicit invocation is off, so a gated run starts only on request", () => {
  assert.match(
    read("skills/zlak-flow/agents/openai.yaml"),
    /allow_implicit_invocation: false/,
  );
});

test("the config template is a generated, parseable copy", () => {
  JSON.parse(read("config/coder.example.json"));
});

test("install.sh is executable and installs, then reports up to date", () => {
  assert.ok((statSync(`${root}install.sh`).mode & 0o111) !== 0, "executable");
  const target = mkdtempSync(`${tmpdir()}/zlak-codex-`);
  const dry = install("--target", target, "--dry-run");
  assert.equal(dry.status, 0);
  assert.match(dry.stdout, /would install/);
  assert.equal(readdirOrEmpty(target).length, 0, "dry run writes nothing");

  const first = install("--target", target);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(
    readFileSync(`${target}/zlak-flow/SKILL.md`, "utf8"),
    read("skills/zlak-flow/SKILL.md"),
  );
  assert.match(
    readFileSync(`${target}/zlak-flow/agents/openai.yaml`, "utf8"),
    /allow_implicit_invocation/,
  );
  assert.match(install("--target", target).stdout, /up to date/);
});

test("install.sh refuses to overwrite a changed copy without --force", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-codex-`);
  install("--target", target);
  writeFileSync(`${target}/zlak-flow/SKILL.md`, "my edits\n");
  const refused = install("--target", target);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /--force/);
  assert.equal(
    readFileSync(`${target}/zlak-flow/SKILL.md`, "utf8"),
    "my edits\n",
  );
  assert.equal(install("--target", target, "--force").status, 0);
  assert.equal(
    readFileSync(`${target}/zlak-flow/SKILL.md`, "utf8"),
    read("skills/zlak-flow/SKILL.md"),
  );
});

test("install.sh rejects an unknown option", () => {
  assert.equal(install("--nope").status, 2);
});

/** List a directory, or nothing when it does not exist yet. */
function readdirOrEmpty(dir) {
  return execFileSync("ls", ["-A", dir], { encoding: "utf8" })
    .split("\n")
    .filter(Boolean);
}
