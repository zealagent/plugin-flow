/**
 * Offline checks for the zlak-flow Cursor plugin.
 *
 * - The plugin manifest is named zlak-flow and carries the package version.
 * - The command has name and description and ends with the run input.
 * - The planner and reviewer agents are readonly.
 * - install.mjs installs into a chosen directory (and optionally a project's .cursor/agents),
 *   is idempotent, and never overwrites a changed file without --force.
 */
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(root + path, "utf8");

/** Split a markdown file into flat frontmatter fields and body. */
const frontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  assert.ok(match, "frontmatter present");
  const fields = {};
  for (const line of match[1].split("\n")) {
    const pair = line.match(/^([a-z-]+):\s*(.*)$/);
    if (pair) fields[pair[1]] = pair[2];
  }
  return { fields, body: match[2] };
};

const manifest = JSON.parse(read(".cursor-plugin/plugin.json"));
const pkg = JSON.parse(read("package.json"));
const command = frontmatter(read("commands/zlak-flow.md"));
const install = (...args) =>
  spawnSync("node", [`${root}install.mjs`, ...args], { encoding: "utf8" });

test("the manifest is named zlak-flow and matches package.json", () => {
  assert.equal(manifest.name, "zlak-flow");
  assert.equal(manifest.version, pkg.version);
});

test("the command has name and description and ends with the run input", () => {
  assert.equal(command.fields.name, "zlak-flow");
  assert.ok(command.fields.description.length > 40);
  assert.ok(command.body.includes("Generated by packages/core"));
  assert.match(command.body.trimEnd(), /read the message itself\.$/);
});

for (const name of ["zlak-flow-planner", "zlak-flow-reviewer"]) {
  test(`${name} is a readonly subagent`, () => {
    const { fields } = frontmatter(read(`agents/${name}.md`));
    assert.equal(fields.name, name);
    assert.equal(fields.readonly, "true");
  });
}

test("install.mjs installs the plugin, then reports up to date", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-cursor-`);
  const dry = install("--target", target, "--dry-run");
  assert.equal(dry.status, 0);
  assert.match(dry.stdout, /would install/);
  assert.equal(readdirSync(target).length, 0, "dry run writes nothing");
  const first = install("--target", target);
  assert.equal(first.status, 0, first.stderr);
  assert.equal(
    read("commands/zlak-flow.md"),
    readFileSync(`${target}/commands/zlak-flow.md`, "utf8"),
  );
  assert.equal(
    read(".cursor-plugin/plugin.json"),
    readFileSync(`${target}/.cursor-plugin/plugin.json`, "utf8"),
  );
  assert.match(install("--target", target).stdout, /up to date/);
});

test("--project also installs the agents into the project's .cursor/agents", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-cursor-`);
  const project = mkdtempSync(`${tmpdir()}/zlak-cursor-project-`);
  assert.equal(install("--target", target, "--project", project).status, 0);
  assert.deepEqual(
    readdirSync(`${project}/.cursor/agents`).sort(),
    readdirSync(`${root}agents`).sort(),
  );
});

test("install.mjs refuses to overwrite a changed file without --force", () => {
  const target = mkdtempSync(`${tmpdir()}/zlak-cursor-`);
  install("--target", target);
  writeFileSync(`${target}/commands/zlak-flow.md`, "my edits\n");
  const refused = install("--target", target);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /--force/);
  assert.equal(
    readFileSync(`${target}/commands/zlak-flow.md`, "utf8"),
    "my edits\n",
  );
  assert.equal(install("--target", target, "--force").status, 0);
  assert.equal(
    readFileSync(`${target}/commands/zlak-flow.md`, "utf8"),
    read("commands/zlak-flow.md"),
  );
  assert.equal(install("--nope").status, 2);
});
